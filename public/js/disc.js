/**
 * @param {string[]} answers - array of type keys, one per answered question
 * @returns {{counts: Record<string, number>, percents: Record<string, number>, primary: string|null, secondary: string|null}}
 */
export function scoreAnswers(answers) {
  if (!Array.isArray(answers)) throw new TypeError('answers must be an array');
  const counts = Object.fromEntries(TYPE_KEYS.map((k) => [k, 0]));
  for (const key of answers) {
    if (!TYPE_KEYS.includes(key)) throw new RangeError(`Unknown DISC type: ${key}`);
    counts[key] += 1;
  }
  const total = answers.length;
  const percents = Object.fromEntries(
    TYPE_KEYS.map((k) => [k, total === 0 ? 0 : Math.round((counts[k] / total) * 100)]),
  );
  // Stable sort keeps D-I-S-C order on ties.
  const ranked = [...TYPE_KEYS].sort((a, b) => counts[b] - counts[a]);
  const primary = total === 0 ? null : ranked[0];
  const secondary = total === 0 || counts[ranked[1]] === 0 ? null : ranked[1];
  return { counts, percents, primary, secondary };
}
