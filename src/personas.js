export const PERSONAS = CHARACTERS;

/**
 * System prompt for the 1:1 trainer: the persona opens the scene, the user is the other person in it.
 * @param {string} id
 * @param {string} scenario
 * @param {number} intro
 */
export function trainerSystem(id, scenario, intro) {
  return `${PERSONAS[id].character}

${sceneText(scenario, intro, sceneCue(scenario, intro))}
Твой собеседник — живой человек, с которым тебя свела эта сцена (в романтических сценах — твой партнёр).
${COMMON_RULES}`;
}

export const PERSONA_IDS = Object.freeze(ARCHETYPE_IDS.filter((id) => id in PERSONAS));

/**
 * Public view of a persona for the client: never includes the system prompt.
 * @param {string} id
 * @returns {{name: string, bio: string}}
 */
export function publicPersona(id) {
  const { name, bio } = PERSONAS[id];
  return { name, bio };
}
